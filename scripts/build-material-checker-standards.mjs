import {createHash} from 'node:crypto';
import {readFile, writeFile} from 'node:fs/promises';
import {dirname, join, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const auditRoot = join(root, 'source-assets', 'grade-specification-lookup');
const modules = ['audited-a36.js', 'audited-g40.js', 'audited-z245.js'];
const sources = await Promise.all(modules.map(name => readFile(join(auditRoot, name), 'utf8')));
const adapter = await readFile(join(root, 'source-assets', 'material-checker', 'standards-adapter.js'), 'utf8');
const bundle = `/* Generated by scripts/build-material-checker-standards.mjs.\n * Authoritative attachment audits are shared with Material Specification Lookup.\n * Edit the source audit modules or adapter; do not edit this bundle.\n */\n(function (root, factory) {\n  'use strict';\n  if (typeof module === 'object' && module.exports) module.exports = factory();\n  else root.MaterialCheckerStandards = factory();\n}(typeof globalThis !== 'undefined' ? globalThis : this, function () {\n  'use strict';\n${sources.join('\n\n')}\n${adapter}\n  return MaterialCheckerStandards;\n}));\n`;
await writeFile(join(root, 'tools', 'material-checker-standards.js'), bundle, 'utf8');
console.log(`Shared material checker standards rebuilt: ${createHash('sha256').update(bundle).digest('hex')}`);
