import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

// ExamPreview reuses the real exam simulator's look. Rather than copying the
// styles (and letting them drift), the build lifts them from their single
// sources: the <style> block in test-bank.html and the answer-review styles in
// test-bank-current-attempt-review.js. Only CSS is extracted; no question data.
const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');

export async function extractExamUiCss(root = ROOT) {
  const page = await readFile(join(root, 'test-bank.html'), 'utf8');
  const head = page.slice(0, page.indexOf('</head>'));
  const simulator = /<style>([\s\S]*?)<\/style>/.exec(head);
  if (!simulator) throw new Error('Simulator styles not found in test-bank.html.');
  const reviewSource = await readFile(join(root, 'test-bank-current-attempt-review.js'), 'utf8');
  const review = /style\.textContent = `([\s\S]*?)`;/.exec(reviewSource);
  if (!review || review[1].includes('${')) throw new Error('Answer-review styles not found or not static.');
  // Contextual formula-pane styles (used by the PMP formula sheet), injected at
  // runtime by test-bank-formulas.js in the real exam.
  const formulasSource = await readFile(join(root, 'test-bank-formulas.js'), 'utf8');
  const pane = /style\.textContent = \[([\s\S]*?)\]\.join\(''\);/.exec(formulasSource);
  if (!pane) throw new Error('Formula-pane styles not found in test-bank-formulas.js.');
  const paneCss = pane[1].split('\n').map(l => l.trim().replace(/,$/, '')).filter(Boolean)
    .map(l => { if (!/^'.*'$/.test(l) || l.slice(1, -1).includes("'")) throw new Error('Formula-pane styles are not static.'); return l.slice(1, -1); }).join('');
  const css = '/* Generated by scripts/build-exampreview.mjs from test-bank.html, test-bank-current-attempt-review.js and test-bank-formulas.js. Do not edit. */\n'
    + simulator[1].trim() + '\n/* Answer review */\n' + review[1].trim() + '\n/* Contextual formula pane */\n' + paneCss + '\n';
  if (/["']?stem["']?\s*:\s*["'`]/.test(css)) throw new Error('Unexpected content in extracted styles.');
  return css;
}

// The Formulas, Tables and Calc tools are lifted verbatim from test-bank.html
// too: the formula sheets (REFS.cssbb, REFS.cssgb, which shares it, and REFS.mbb,
// the Black Belt sheet plus the MBB-only groups), the calculator engine and the
// drawer/calculator overlay code. The Tables drawer uses the shared public
// /test-bank-tables.js, exactly as the real exam does.
function between(src, start, end) {
  const a = src.indexOf(start);
  const b = a < 0 ? -1 : src.indexOf(end, a + start.length);
  if (a < 0 || b < 0) throw new Error(`Exam tool code not found in test-bank.html: ${start.trim()}`);
  return src.slice(a, b).trim();
}

export async function extractExamToolsJs(root = ROOT) {
  const page = await readFile(join(root, 'test-bank.html'), 'utf8');
  const refs = between(page, '  var REFS={', '  function factorial(');
  const calc = between(page, '  function factorial(', '  function fmtClock(');
  const tools = between(page, '  function calcKeys(){', '  function isAnswerRevealed(');
  if (!/REFS=\{\s*cssbb:\[/.test(refs) || /stem\s*:/.test(refs + calc + tools)) throw new Error('Unexpected content in extracted exam tools.');
  return '/* Generated by scripts/build-exampreview.mjs from test-bank.html. Do not edit. */\n'
    + "(function(){'use strict';\n"
    + "  var current=(document.body&&document.body.dataset.examPreview)||'cssbb', calcExpr='';\n"
    + "  function esc(s){return String(s).replace(/[&<>\"]/g,function(c){return {'&':'&amp;','<':'&lt;','>':'&gt;','\"':'&quot;'}[c];});}\n"
    + '  ' + refs + '\n  ' + calc + '\n  ' + tools + '\n'
    + "  // test-bank-formulas.js (the real CQE formula pane) fills REFS.cqe through window.__TB.REFS, as in the real exam.\n"
    + '  if(!window.__TB)window.__TB={REFS:REFS};\n'
    + '  window.__ExamPreviewTools={build:buildTools,toggle:toggleTool,stop:stopTools,refresh:renderRefs,calcEval:calcEval};\n})();\n';
}

export async function buildExamPreview(root = ROOT, destination = join(root, 'public-site')) {
  const css = await extractExamUiCss(root);
  await mkdir(join(destination, 'exam-preview'), { recursive: true });
  await writeFile(join(destination, 'exam-preview', 'exam-ui.css'), css);
  // The real PMP exam's formula pane, copied verbatim. It holds formulas from
  // the public PMP Formula Encyclopedia lesson, no questions or answers.
  const pmpFormulas = await readFile(join(root, 'test-bank-pmp-formulas.js'), 'utf8');
  if (/["']?stem["']?\s*:\s*["'`]/.test(pmpFormulas)) throw new Error('Unexpected question content in test-bank-pmp-formulas.js.');
  await writeFile(join(destination, 'exam-preview', 'test-bank-pmp-formulas.js'), pmpFormulas);
  // The real CQE exam's formula pane, copied verbatim: its 94-formula sheet,
  // installFallbackRefs() and the context-aware 'Recommended for the current
  // question' view. It holds formulas only, no questions or answers.
  const cqeFormulas = await readFile(join(root, 'test-bank-formulas.js'), 'utf8');
  if (/["']?stem["']?\s*:\s*["'`]/.test(cqeFormulas)) throw new Error('Unexpected question content in test-bank-formulas.js.');
  await writeFile(join(destination, 'exam-preview', 'test-bank-formulas.js'), cqeFormulas);
  const tools = await extractExamToolsJs(root);
  await writeFile(join(destination, 'exam-preview', 'exam-tools.js'), tools);
  console.log(`ExamPreview: wrote exam-preview/exam-tools.js (${tools.length} bytes) from the real exam tools.`);
  console.log(`ExamPreview: wrote exam-preview/exam-ui.css (${css.length} bytes) from the real exam styles.`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await buildExamPreview();
